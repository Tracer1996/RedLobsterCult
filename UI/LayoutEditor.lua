-- Vanilla can occasionally miss OnDragStop when the cursor leaves a draggable
-- overlay.  This watchdog releases every editor drag as soon as the physical
-- left mouse button is no longer held.
if not RLC_LAYOUT_EDITOR.dragWatchdog then
  local watchdog=CreateFrame("Frame",nil,UIParent)
  RLC_LAYOUT_EDITOR.dragWatchdog=watchdog
  watchdog:SetScript("OnUpdate",function()
    if RLC_LAYOUT_EDITOR and RLC_LAYOUT_EDITOR:HasActiveDrag()
      and IsMouseButtonDown and not IsMouseButtonDown("LeftButton") then
      RLC_LAYOUT_EDITOR:StopAllDragging()
      RLC_LAYOUT_EDITOR:RefreshControl()
    end
  end)
end

function RLC_LAYOUT_EDITOR:ShowDumpWindow()
  local text=self:BuildDumpText()
  local f=self:CreateDumpWindow()
  self.dumpEditBox:SetText(text)
  local lineCount=1
  local p=1
  while true do
    local a,b=string.find(text,"\n",p)
    if not a then break end
    lineCount=lineCount+1; p=b+1
  end
  self.dumpEditBox:SetHeight(math.max(420,lineCount*14+30))
  f:Show()
  self.dumpEditBox:SetFocus()
  self.dumpEditBox:HighlightText()
  Msg("Dump opened in a copyable text window.")
end

-- Replace chat-only dump with a copyable text window while still preserving chat summary.
function RLC_LAYOUT_EDITOR:Dump()
  self:ShowDumpWindow()
end

