local function CopyLayoutPosition(source)
  if not source then return nil end
  return {
    x=source.x, y=source.y, w=source.w, h=source.h,
    point=source.point, relativePoint=source.relativePoint,
  }
end

local function InstallApprovedLayout(db)
  db.positions = {}
  local key, position
  for key, position in pairs(RLC_LAYOUT_EDITOR.APPROVED_LAYOUT) do
    db.positions[key] = CopyLayoutPosition(position)
  end
  db.schemaVersion = RLC_LAYOUT_EDITOR.APPROVED_LAYOUT_VERSION
end

local function DB()
  RLC_DB = RLC_DB or {}
  RLC_DB.layoutEditor = RLC_DB.layoutEditor or {}
  RLC_DB.layoutEditor.positions = RLC_DB.layoutEditor.positions or {}
  if RLC_DB.layoutEditor.schemaVersion ~= RLC_LAYOUT_EDITOR.APPROVED_LAYOUT_VERSION then
    InstallApprovedLayout(RLC_DB.layoutEditor)
  end
  return RLC_DB.layoutEditor
end

local function Msg(s)
  if DEFAULT_CHAT_FRAME then DEFAULT_CHAT_FRAME:AddMessage("|cFFFFD700RLC Config:|r " .. tostring(s or "")) end
end

local function Round(n)
  n = tonumber(n) or 0
  if n >= 0 then return math.floor(n + 0.5) end
  return math.ceil(n - 0.5)
end

local function Cursor()
  local x, y = GetCursorPosition()
  local scale = UIParent:GetEffectiveScale() or 1
  return x / scale, y / scale
end

function RLC_LAYOUT_EDITOR:Capture(frame)
  if not frame or not frame.GetPoint then return nil end
  local point, relativeTo, relativePoint, x, y = frame:GetPoint(1)
  if not point then return nil end
  return { point=point, relativeTo=relativeTo or frame:GetParent(), relativePoint=relativePoint or point, x=x or 0, y=y or 0 }
end

function RLC_LAYOUT_EDITOR:Register(key, frame)
  if not key or not frame then return end
  local e = self.registry[key]
  if not e then
    e = { key=key }
    self.registry[key] = e
    table.insert(self.order, key)
  end
  e.frame = frame
  if not e.defaultAnchor then e.defaultAnchor = self:Capture(frame) end
  if not e.defaultWidth and frame.GetWidth then e.defaultWidth = frame:GetWidth() end
  if not e.defaultHeight and frame.GetHeight then e.defaultHeight = frame:GetHeight() end
  self:Apply(key)
  if self.enabled then self:EnsureOverlay(key); self:SyncOverlay(key); e.overlay:Show() end
end

function RLC_LAYOUT_EDITOR:GetSaved(key) return DB().positions[key] end

function RLC_LAYOUT_EDITOR:EnsureSaved(key)
  local e = self.registry[key]
  if not e or not e.defaultAnchor then return nil end
  local s = self:GetSaved(key)
  if not s then
    s = CopyLayoutPosition(self.APPROVED_LAYOUT[key])
    if not s then
      s = {
        point=e.defaultAnchor.point, relativePoint=e.defaultAnchor.relativePoint,
        x=e.defaultAnchor.x or 0, y=e.defaultAnchor.y or 0,
        w=e.defaultWidth or 20, h=e.defaultHeight or 20,
      }
    end
    DB().positions[key] = s
  end
  if not s.w then s.w = e.defaultWidth or 20 end
  if not s.h then s.h = e.defaultHeight or 20 end
  return s
end

function RLC_LAYOUT_EDITOR:Apply(key)
  local e = self.registry[key]
  if not e or not e.frame or not e.defaultAnchor then return end
  local s = self:GetSaved(key) or self.APPROVED_LAYOUT[key]
  local a = e.defaultAnchor
  local point = (s and s.point) or a.point
  local relativePoint = (s and s.relativePoint) or a.relativePoint or point
  local x = (s and s.x) or a.x or 0
  local y = (s and s.y) or a.y or 0
  local w = (s and s.w) or e.defaultWidth
  local h = (s and s.h) or e.defaultHeight
  e.frame:ClearAllPoints()
  e.frame:SetPoint(point, a.relativeTo or e.frame:GetParent(), relativePoint, x, y)
  if w and e.frame.SetWidth then e.frame:SetWidth(math.max(12, w)) end
  if h and e.frame.SetHeight then e.frame:SetHeight(math.max(12, h)) end
end

function RLC_LAYOUT_EDITOR:StopAllDragging()
  local i, e, overlay
  for i=1,table.getn(self.order) do
    e = self.registry[self.order[i]]
    overlay = e and e.overlay
    if overlay then
      overlay.dragging = false
      if overlay.resizeGrip then overlay.resizeGrip.resizing = false end
    end
  end
  if self.activeMovingFrame and self.activeMovingFrame.StopMovingOrSizing then
    self.activeMovingFrame:StopMovingOrSizing()
  end
  self.activeMovingFrame = nil
end

function RLC_LAYOUT_EDITOR:HasActiveDrag()
  if self.activeMovingFrame then return true end
  local i, e, overlay
  for i=1,table.getn(self.order) do
    e = self.registry[self.order[i]]
    overlay = e and e.overlay
    if overlay and (overlay.dragging or (overlay.resizeGrip and overlay.resizeGrip.resizing)) then
      return true
    end
  end
  return false
end

function RLC_LAYOUT_EDITOR:BeginMoving(frame)
  self:StopAllDragging()
  self.activeMovingFrame = frame
  if frame and frame.StartMoving then frame:StartMoving() end
end

function RLC_LAYOUT_EDITOR:ApplyAll()
  local i
  for i=1,table.getn(self.order) do self:Apply(self.order[i]) end
  if RLC_RefreshAshenBG then RLC_RefreshAshenBG() end
end

function RLC_LAYOUT_EDITOR:GetSelectedKey()
  local n = table.getn(self.order)
  if n == 0 then return nil end
  if self.selectedIndex < 1 then self.selectedIndex = n end
  if self.selectedIndex > n then self.selectedIndex = 1 end
  return self.order[self.selectedIndex]
end

function RLC_LAYOUT_EDITOR:SelectDelta(d)
  self.selectedIndex = self.selectedIndex + (d or 1)
  self:GetSelectedKey()
  self:RefreshControl()
  self:RefreshHighlights()
end

function RLC_LAYOUT_EDITOR:Nudge(dx,dy)
  local key = self:GetSelectedKey(); if not key then return end
  local s = self:EnsureSaved(key); if not s then return end
  s.x = (s.x or 0) + (dx or 0); s.y = (s.y or 0) + (dy or 0)
  self:Apply(key); self:SyncOverlay(key); self:RefreshControl()
end

function RLC_LAYOUT_EDITOR:Resize(dw,dh)
  local key = self:GetSelectedKey(); if not key then return end
  local s = self:EnsureSaved(key); if not s then return end
  s.w = math.max(12, (s.w or 20) + (dw or 0)); s.h = math.max(12, (s.h or 20) + (dh or 0))
  self:Apply(key); self:SyncOverlay(key); self:RefreshControl()
end

function RLC_LAYOUT_EDITOR:EnsureOverlay(key)
  local e = self.registry[key]
  if not e or not e.frame or e.overlay then return end
  local o = CreateFrame("Frame", nil, e.frame:GetParent())
  e.overlay = o
  o.owner = self; o.key = key
  o:SetFrameStrata("TOOLTIP"); o:EnableMouse(true); o:RegisterForDrag("LeftButton")
  o:SetBackdrop({bgFile="Interface\\Tooltips\\UI-Tooltip-Background",edgeFile="Interface\\Tooltips\\UI-Tooltip-Border",tile=true,tileSize=16,edgeSize=10,insets={left=2,right=2,top=2,bottom=2}})
  o:SetBackdropColor(0.05,0.35,0.08,0.16); o:SetBackdropBorderColor(0.1,1,0.2,0.9)
  local t=o:CreateFontString(nil,"OVERLAY","GameFontNormalSmall"); t:SetPoint("CENTER",o,"CENTER",0,0); t:SetTextColor(1,0.9,0.15); t:SetText(key); o.text=t
  local grip=CreateFrame("Frame",nil,o); grip:SetWidth(16); grip:SetHeight(16); grip:SetPoint("BOTTOMRIGHT",o,"BOTTOMRIGHT",0,0); grip:EnableMouse(true); grip:RegisterForDrag("LeftButton")
  local gt=grip:CreateTexture(nil,"OVERLAY"); gt:SetAllPoints(grip); gt:SetTexture("Interface\\ChatFrame\\UI-ChatIM-SizeGrabber-Up")
  o.resizeGrip=grip

  o:SetScript("OnDragStart", function()
    local owner=this.owner; local s=owner:EnsureSaved(this.key); if not s then return end
    owner:StopAllDragging()
    local x,y=Cursor(); this.dragging=true; this.startX=x; this.startY=y; this.baseX=s.x or 0; this.baseY=s.y or 0
  end)
  o:SetScript("OnDragStop", function() this.owner:StopAllDragging(); this.owner:RefreshControl() end)
  o:SetScript("OnMouseUp", function() this.owner:StopAllDragging(); this.owner:RefreshControl() end)
  o:SetScript("OnUpdate", function()
    if not this.dragging then return end
    if IsMouseButtonDown and not IsMouseButtonDown("LeftButton") then
      this.owner:StopAllDragging(); this.owner:RefreshControl(); return
    end
    local x,y=Cursor(); local owner=this.owner; local s=owner:EnsureSaved(this.key)
    s.x = Round(this.baseX + (x-this.startX)); s.y = Round(this.baseY + (y-this.startY))
    owner:Apply(this.key); owner:SyncOverlay(this.key)
  end)

  grip:SetScript("OnDragStart", function()
    local parent=this:GetParent(); local owner=parent.owner; local s=owner:EnsureSaved(parent.key); if not s then return end
    owner:StopAllDragging()
    local x,y=Cursor(); this.resizing=true; this.startX=x; this.startY=y; this.baseW=s.w or parent:GetWidth(); this.baseH=s.h or parent:GetHeight()
  end)
  grip:SetScript("OnDragStop", function() local owner=this:GetParent().owner; owner:StopAllDragging(); owner:RefreshControl() end)
  grip:SetScript("OnMouseUp", function() local owner=this:GetParent().owner; owner:StopAllDragging(); owner:RefreshControl() end)
  grip:SetScript("OnUpdate", function()
    if not this.resizing then return end
    if IsMouseButtonDown and not IsMouseButtonDown("LeftButton") then
      local owner=this:GetParent().owner; owner:StopAllDragging(); owner:RefreshControl(); return
    end
    local parent=this:GetParent(); local owner=parent.owner; local s=owner:EnsureSaved(parent.key); local x,y=Cursor()
    s.w=math.max(12,Round(this.baseW+(x-this.startX))); s.h=math.max(12,Round(this.baseH-(y-this.startY)))
    owner:Apply(parent.key); owner:SyncOverlay(parent.key)
  end)
end

function RLC_LAYOUT_EDITOR:SyncOverlay(key)
  local e=self.registry[key]; if not e or not e.frame or not e.overlay then return end
  local a=self:Capture(e.frame); if not a then return end
  e.overlay:ClearAllPoints(); e.overlay:SetPoint(a.point,a.relativeTo,a.relativePoint,a.x,a.y)
  e.overlay:SetWidth(math.max(12,e.frame:GetWidth() or 20)); e.overlay:SetHeight(math.max(12,e.frame:GetHeight() or 20))
end

function RLC_LAYOUT_EDITOR:RefreshHighlights()
  local selected=self:GetSelectedKey(); local i,key,e
  for i=1,table.getn(self.order) do key=self.order[i]; e=self.registry[key]; if e and e.overlay then
    if key==selected then e.overlay:SetBackdropColor(0.4,0.32,0.02,0.25); e.overlay:SetBackdropBorderColor(1,0.85,0.15,1)
    else e.overlay:SetBackdropColor(0.05,0.35,0.08,0.16); e.overlay:SetBackdropBorderColor(0.1,1,0.2,0.9) end
  end end
end

function RLC_LAYOUT_EDITOR:ShowOverlays()
  local i,key,e
  for i=1,table.getn(self.order) do key=self.order[i]; e=self.registry[key]; if e and e.frame then self:EnsureOverlay(key); self:SyncOverlay(key); e.overlay:Show() end end
  self:RefreshHighlights()
end
function RLC_LAYOUT_EDITOR:HideOverlays() self:StopAllDragging(); local i,e for i=1,table.getn(self.order) do e=self.registry[self.order[i]]; if e and e.overlay then e.overlay:Hide() end end end

function RLC_LAYOUT_EDITOR:RefreshControl()
  local f=self.controlFrame; if not f then return end
  local key=self:GetSelectedKey() or "-"; local s=key and self:EnsureSaved(key)
  f.keyText:SetText(key)
  if s then f.posText:SetText("X "..Round(s.x).."  Y "..Round(s.y).."   W "..Round(s.w).."  H "..Round(s.h)) else f.posText:SetText("") end
end

