function RLC_LAYOUT_EDITOR:Enable() self.enabled=true; self:RegisterDefaults(); self:ApplyAll(); self:ShowOverlays(); self:CreateControlFrame():Show(); self:RefreshControl(); Msg("Unlocked. Drag assets or resize with the corner grip.") end
function RLC_LAYOUT_EDITOR:Disable() self:StopAllDragging(); self.enabled=false; self:HideOverlays(); if self.controlFrame then self.controlFrame:Hide() end; self:ApplyAll(); Msg("Locked.") end
