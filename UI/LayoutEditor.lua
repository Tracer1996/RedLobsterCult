function RLC_LAYOUT_EDITOR:ForcePersistentCharacterTabs()
  if not RLC or not RLC.UI or not RLC.UI.navSubtabButtons then return end
  local ui = RLC.UI
  local defs = {
    {tab="me", label="My Stats", width=72},
    {tab="leaderWeek", label="Weekly", width=62},
    {tab="leaderLife", label="Lifetime", width=68},
    {tab="achievements", label="Achievements", width=92},
    {tab="shinobiReputation", label="Cult Reputation", width=108},
    {tab="badges", label="Badges", width=66},
    {tab="titles", label="Titles", width=60},
    {tab="roster", label="Roster", width=62},
    {tab="shoutouts", label="Shoutouts", width=82},
  }
  local i, btn, def
  for i=1,table.getn(ui.navSubtabButtons) do
    btn = ui.navSubtabButtons[i]
    def = defs[i]
    if btn and def then
      btn.targetTab = def.tab
      btn.categoryKey = "character"
      btn.rlcTexture = "rlc_btn_blank"
      if btn.text then
        btn.text:SetText(def.label)
        if ui.activeTab == def.tab then
          btn.text:SetTextColor(1,0.88,0.35)
        else
          btn.text:SetTextColor(0.88,0.88,0.88)
        end
      end
      btn:SetWidth(def.width)
      if ApplyAshenUniversalButtonTexture then ApplyAshenUniversalButtonTexture(btn) end
      if btn._ashenBtnNormal then btn._ashenBtnNormal:Show(); btn._ashenBtnNormal:SetAlpha(1) end
      if btn._ashenBtnPushed then
        if ui.activeTab == def.tab then btn._ashenBtnPushed:Show() else btn._ashenBtnPushed:Hide() end
      end
      btn:Show()
    elseif btn then
      btn:Hide()
    end
  end
end

function RLC_LAYOUT_EDITOR:BuildDumpText()
  local lines = {}
  table.insert(lines, "RLC CONFIG DUMP")
  table.insert(lines, "Version: " .. tostring(RLC and RLC.version or "unknown"))
  table.insert(lines, "")
  local i,key,s
  for i=1,table.getn(self.order) do
    key=self.order[i]
    s=self:EnsureSaved(key)
    if s then
      table.insert(lines, key .. " = { x="..Round(s.x)..", y="..Round(s.y)..", w="..Round(s.w)..", h="..Round(s.h)..", point=\""..tostring(s.point).."\", relativePoint=\""..tostring(s.relativePoint).."\" }")
    end
  end
  return table.concat(lines, "\n")
end

